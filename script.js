function esc(value = "") {

  return String(value).replace(
    /[&<>"']/g,

    function (character) {

      return {
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;"
      }[character];

    }
  );
}


function listify(value) {

  if (!value) {
    return [];
  }

  if (Array.isArray(value)) {
    return value;
  }

  try {
    return JSON.parse(value);
  } catch (error) {
    return String(value)
      .split(/\n+/)
      .map(item => item.trim())
      .filter(Boolean);
  }
}


