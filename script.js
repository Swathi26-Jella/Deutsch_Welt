// 16. GRAMMAR PAGE
// =====================================================

async function renderGrammar() {

  const grid =
    document.getElementById(
      "grammar-grid"
    );


  const filterHost =
    document.getElementById(
      "grammar-filters"
    );


  if (
    !grid ||
    !filterHost
  ) {
    return;
  }


  const result =
    await getRows(
      "grammar_topics",
      {
        order:
          "sort_order"
      }
    );


  if (
    result.error ||
    !result.data ||
    !result.data.length
  ) {

    grid.innerHTML = `

      <div class="empty-state">

        Noch keine Grammatikthemen in Supabase.

      </div>

    `;

    return;

  }


  const rows =
    result.data.filter(
      row =>
        row.published !== false
    );


  let selectedLevel =
    "Alle";


  const levels = [

    "Alle",

    ...new Set(
      rows
        .map(
          row =>
            row.level
        )
        .filter(Boolean)
    )

  ];


  function draw() {

    createFilterButtons(

      filterHost,

      levels,

      selectedLevel,

      function (value) {

        selectedLevel =
          value;

        draw();

      }

    );


    const filtered =
      rows.filter(
        row =>

          selectedLevel === "Alle" ||

          row.level ===
            selectedLevel

      );


    grid.innerHTML =
      filtered
        .map(
          grammar => `

            <article
              class="grammar-card"
            >

              <span class="level-badge">

                ${esc(
                  grammar.level
                )}

              </span>


              <h3>

                ${esc(
                  grammar.title
                )}

              </h3>


              <p>

                ${esc(
                  grammar.short_explanation ||
                  ""
                )}

              </p>


              <div class="rule">

                ${esc(
                  grammar.rule_preview ||
                  ""
                )}

              </div>


              <br>


              <button
                class="button secondary"
                data-grammar-open="${esc(
                  grammar.id
                )}"
              >

                Ansehen

              </button>

            </article>

          `
        )
        .join("");


    grid
      .querySelectorAll(
        "[data-grammar-open]"
      )
      .forEach(
        button => {

          button.onclick =
            async function () {

              const result =
                await getRows(
                  "grammar_topics",
                  {
                    eq: {
                      id:
                        button.dataset
                          .grammarOpen
                    }
                  }
                );


              if (
                !result.error &&
                result.data &&
                result.data.length
              ) {

                openModal(
                  result.data[0].title,

                  renderDetail(
                    result.data[0]
                  )
                );

              }

            };

        }
      );

  }


  draw();

}


