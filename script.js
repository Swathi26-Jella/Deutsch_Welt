// 17. ESC CLOSES MODAL
// =====================================================

document.addEventListener(
  "keydown",

  function (event) {

    if (
      event.key === "Escape"
    ) {

      const modal =
        document.querySelector(
          ".detail-modal.open"
        );


      if (modal) {

        modal.classList.remove(
          "open"
        );

      }

    }

  }

);


