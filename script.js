async function renderVocabulary() {

  const grid =
    document.getElementById(
      "vocab-grid"
    );


  const filterHost =
    document.getElementById(
      "vocab-filters"
    );


  if (
    !grid ||
    !filterHost
  ) {
    return;
  }


  const result =
    await getRows(
      "vocabulary",
      {
        order:
          "sort_order"
      }
    );


  if (
    result.error ||
    !result.data ||
    !result.data.length
  ) {

    grid.innerHTML = `

      <div class="empty-state">

        Noch kein Wortschatz in Supabase.

      </div>

    `;

    return;

  }


  const rows =
    result.data.filter(
      row =>
        row.published !== false
    );


  let selectedLevel =
    "Alle";


  let selectedCategory =
    "Alle";


  const levels = [

    "Alle",

    ...new Set(
      rows
        .map(
          row =>
            row.level
        )
        .filter(Boolean)
    )

  ];


  const categories = [

    "Alle",

    ...new Set(
      rows
        .map(
          row =>
            row.category
        )
        .filter(Boolean)
    )

  ];


  function draw() {

    filterHost.innerHTML = "";


    const levelFilters =
      document.createElement(
        "div"
      );


    levelFilters.className =
      "filters";


    createFilterButtons(
      levelFilters,

      levels,

      selectedLevel,

      function (value) {

        selectedLevel =
          value;

        draw();

      }
    );


    const categoryFilters =
      document.createElement(
        "div"
      );


    categoryFilters.className =
      "filters";


    createFilterButtons(
      categoryFilters,

      categories,

      selectedCategory,

      function (value) {

        selectedCategory =
          value;

        draw();

      }
    );


    filterHost.append(
      levelFilters,
      categoryFilters
    );


    const filtered =
      rows.filter(
        row =>

          (
            selectedLevel === "Alle" ||
            row.level === selectedLevel
          )

          &&

          (
            selectedCategory === "Alle" ||
            row.category === selectedCategory
          )

      );


    grid.innerHTML =
      filtered
        .map(
          vocabulary => `

            <article
              class="vocab-card"
            >

              <span class="eyebrow">

                ${esc(
                  vocabulary.level
                )}

                ·

                ${esc(
                  vocabulary.category
                )}

              </span>


              <div class="vocab-word">

                ${esc(
                  vocabulary.article
                    ? vocabulary.article + " "
                    : ""
                )}

                ${esc(
                  vocabulary.word
                )}

              </div>


              <div class="vocab-meta">

                ${
                  vocabulary.plural
                    ? "Plural: " +
                      esc(
                        vocabulary.plural
                      )
                    : ""
                }


                ${
                  vocabulary.meaning
                    ? " · " +
                      esc(
                        vocabulary.meaning
                      )
                    : ""
                }

              </div>


              <div class="vocab-example">

                ${esc(
                  vocabulary.example ||
                  ""
                )}

              </div>

            </article>

          `
        )
        .join("");


    if (!filtered.length) {

      grid.innerHTML = `

        <div class="empty-state">

          Keine Wörter für diese Auswahl.

        </div>

      `;

    }

  }


  draw();

}


