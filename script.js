function openModal(
  title,
  body
) {

  let modal =
    document.getElementById(
      "detailModal"
    );


  /*
    Create modal only once
  */

  if (!modal) {

    document.body.insertAdjacentHTML(
      "beforeend",

      `

        <div
          class="detail-modal"
          id="detailModal"
        >

          <div class="modal-card">

            <button
              class="modal-close"
              id="modalClose"
              aria-label="Schließen"
            >
              ✕
            </button>


            <div
              id="modalContent"
            ></div>

          </div>

        </div>

      `

    );


    modal =
      document.getElementById(
        "detailModal"
      );


    const closeButton =
      document.getElementById(
        "modalClose"
      );


    if (closeButton) {

      closeButton.onclick =
        function () {

          modal.classList.remove(
            "open"
          );

        };

    }


    modal.onclick =
      function (event) {

        if (
          event.target === modal
        ) {

          modal.classList.remove(
            "open"
          );

        }

      };

  }


  const content =
    document.getElementById(
      "modalContent"
    );


  content.innerHTML = `

    <span class="eyebrow">
      REVISION
    </span>

    <h2>
      ${esc(title)}
    </h2>

    ${body}

  `;


  modal.classList.add(
    "open"
  );

}


