// 18. START WEBSITE
// =====================================================

(async function init() {

  renderHeader();

  renderFooter();


  /*
    Connect to Supabase
  */

  try {

    await connectSupabase();

  } catch (error) {

    console.error(
      "Supabase connection failed:",
      error
    );

  }


  /*
    Decide what the current
    HTML page needs.
  */

  if (
    page === "home"
  ) {

    await renderLevelCards(
      "home-levels"
    );

  }


  else if (
    page === "learn"
  ) {

    await renderLevelCards(
      "all-levels"
    );

  }


  else if (
    page === "level"
  ) {

    await renderLevelPage(
      document.body.dataset.level
    );

  }


  else if (
    page === "vocabulary"
  ) {

    await renderVocabulary();

  }


  else if (
    page === "grammar"
  ) {

    await renderGrammar();

  }

})();
