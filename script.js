// =====================================================

function createFilterButtons(
  host,
  values,
  current,
  onChange
) {

  host.innerHTML =
    values
      .map(
        value => `

          <button
            class="filter-btn ${
              value === current
                ? "active"
                : ""
            }"
            data-filter="${esc(
              value
            )}"
          >

            ${esc(value)}

          </button>

        `
      )
      .join("");


  host
    .querySelectorAll(
      "[data-filter]"
    )
    .forEach(
      button => {

        button.onclick =
          function () {

            onChange(
              button.dataset.filter
            );

          };

      }
    );

}


