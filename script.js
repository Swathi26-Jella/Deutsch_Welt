// 3. CONNECT TO SUPABASE
// =====================================================

async function connectSupabase() {

  /*
    Do nothing until you enter your credentials.
  */

  if (
    !SUPABASE_URL ||
    SUPABASE_URL.includes("PASTE_") ||

    !SUPABASE_ANON_KEY ||
    SUPABASE_ANON_KEY.includes("PASTE_")
  ) {

    console.warn(
      "Supabase URL and key have not been added yet."
    );

    return false;
  }


  /*
    Load Supabase JavaScript library.
  */

  if (!window.supabase) {

    await new Promise(
      function (resolve, reject) {

        const script =
          document.createElement("script");

        script.src =
          SUPABASE_CDN;

        script.onload = resolve;

        script.onerror = reject;

        document.head.appendChild(script);

      }
    ).catch(
      function (error) {

        console.error(
          "Could not load Supabase library.",
          error
        );

      }
    );

  }


  if (!window.supabase) {

    return false;

  }


  /*
    Create Supabase client.
  */

  db =
    window.supabase.createClient(
      SUPABASE_URL,
      SUPABASE_ANON_KEY
    );


  return true;

}


// =====================================================
// 4. GET DATA FROM SUPABASE
// =====================================================

async function getRows(
  table,
  options = {}
) {

  if (!db) {

    return {
      data: null,
      error:
        new Error("Supabase is not connected.")
    };

  }


  let query =
    db
      .from(table)
      .select(options.select || "*");


  /*
    Equality filters
  */

  if (options.eq) {

    for (
      const [column, value]
      of Object.entries(options.eq)
    ) {

      query =
        query.eq(column, value);

    }

  }


  /*
    Sorting
  */

  if (options.order) {

    query =
      query.order(
        options.order,
        {
          ascending: true
        }
      );

  }


  return await query;

}


